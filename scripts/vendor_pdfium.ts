/**
 * Vendor one pinned release of bblanchon/pdfium-binaries' WebAssembly build
 * into `vendor/pdfium/`, which is committed, so builds never need the network.
 *
 * The release's glue (`lib/pdfium.js`) is a classic Emscripten script that
 * sets a global `Module`. It isn't an ES module and isn't on npm, so this
 * wraps it into one: `vendor/pdfium/pdfium.mjs` default-exports
 * `createPdfium(moduleArg)`, which resolves with the initialised module.
 *
 * Usage:
 *   bun scripts/vendor_pdfium.ts           vendor the pinned release
 *   bun scripts/vendor_pdfium.ts --check   list the releases newer than the pin
 *
 * It refuses a tarball whose hash doesn't match `SHA256`, and leaves
 * `vendor/pdfium/` untouched on any failure.
 *
 * Updating (monthly, and at once for a PDFium security fix that affects
 * parsing; docs/plan_upstream_pdfium.md phase 6):
 *
 * 1. `bun run pdfium:check`. It lists each newer release with its date and the
 *    SHA-256 GitHub publishes for its `pdfium-wasm.tgz`. For security fixes,
 *    see the Chrome Releases blog: fixes in PDFium are listed under it.
 * 2. Set `TAG` and `SHA256` below to the chosen release, from that list.
 * 3. `bun run pdfium:vendor`, then `bun run check`.
 * 4. Review each failure before accepting anything:
 *    - render hashes: `HOVER_DUMP_RENDERS=<dir> bun test test/engine/render.test.ts`
 *      on the old and the new pin, and diff the PNGs side by side;
 *    - text and analysis snapshots: a change in PDFium's character list
 *      moves the indices the extractors key off;
 *    - saved-annotation snapshots: compare in Preview, Acrobat and Chrome;
 *    - `test/engine/pdfium_regressions.test.ts`: known upstream regressions
 *      Hover is pinned against. A failure there means the bump crosses one;
 *      see the test for what to do.
 *    Then `bun test -u`, and confirm only the reviewed snapshots changed.
 * 5. Record the bump, with the reason for each changed golden, in the log in
 *    docs/plan_upstream_pdfium.md phase 6.
 * 6. Open a paper in the built extension in Chrome, Firefox and Safari; then
 *    ship.
 */

import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import {
  cpSync,
  existsSync,
  mkdirSync,
  mkdtempSync,
  readFileSync,
  readdirSync,
  renameSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";

/**
 * Pinned below chromium/8111, which renders open-path hairline rules light
 * gray (plan, phase 0 item 2). A parsing security fix overrides the pin.
 */
const TAG = "chromium/8100";
/** SHA-256 of the release's `pdfium-wasm.tgz`. */
const SHA256 = "0d68fef9aca2c69f20717c697f90f4fcb7d66a7a30307ad527769d18707394c8";

const URL = `https://github.com/bblanchon/pdfium-binaries/releases/download/${TAG}/pdfium-wasm.tgz`;
const OUT = resolve(import.meta.dirname, "..", "vendor", "pdfium");

/**
 * The glue inside a factory. Three things make it work as a module:
 *
 * - `var Module = moduleArg` sits in the glue's own function scope. The glue
 *   starts with `var Module = typeof Module != "undefined" ? Module : {}`,
 *   which, in the same scope, picks up the caller's object instead of a fresh
 *   one.
 * - `process`, `require`, `module` and `__dirname` are shadowed as
 *   undefined. Under bun or Node the glue would otherwise take its Node path
 *   and `require("fs")`. Given `wasmBinary` it never reads a file anyway.
 * - It resolves on `onRuntimeInitialized` and rejects on `onAbort`, chaining
 *   to any the caller set.
 *
 * Callers must pass `wasmBinary`: the glue would otherwise fetch
 * `pdfium.wasm` relative to a script URL it can't work out inside a module.
 */
function wrap(glue: string): string {
  return `// Generated by scripts/vendor_pdfium.ts from bblanchon/pdfium-binaries
// ${TAG}, lib/pdfium.js. Do not edit; re-run the script.
export default function createPdfium(moduleArg = {}) {
  return new Promise((resolve, reject) => {
    const userInit = moduleArg.onRuntimeInitialized;
    moduleArg.onRuntimeInitialized = () => {
      userInit?.();
      resolve(moduleArg);
    };
    const userAbort = moduleArg.onAbort;
    moduleArg.onAbort = (what) => {
      userAbort?.(what);
      reject(new Error("[PDFium] abort: " + what));
    };
    (function (process, require, module, __dirname) {
var Module = moduleArg;
${glue}
    })(undefined, undefined, undefined, undefined);
  });
}
`;
}

const TYPES = `// Generated by scripts/vendor_pdfium.ts. Do not edit.

export interface CreatePdfiumArg {
  /** The bytes of \`pdfium.wasm\`. Required: the factory can't fetch it. */
  wasmBinary: ArrayBuffer | Uint8Array;
  onRuntimeInitialized?: () => void;
  onAbort?: (what: unknown) => void;
  [key: string]: unknown;
}

/**
 * Instantiate the module. Resolves with the Emscripten module (\`_FPDF_*\`,
 * \`_malloc\`, \`_free\`, the \`HEAP*\` views, \`addFunction\`, \`removeFunction\`)
 * once its runtime is initialised; rejects if it aborts.
 */
export default function createPdfium(moduleArg: CreatePdfiumArg): Promise<unknown>;
`;

function readme(wasmSha256: string): string {
  return `# PDFium (vendored)

Generated by \`scripts/vendor_pdfium.ts\`. Do not edit; re-run the script.

- Release: [bblanchon/pdfium-binaries \`${TAG}\`](https://github.com/bblanchon/pdfium-binaries/releases/tag/${encodeURIComponent(TAG)})
- Tarball: ${URL}
- Tarball SHA-256: \`${SHA256}\`
- \`pdfium.wasm\` SHA-256: \`${wasmSha256}\`

| File | From the release |
| ---- | ---------------- |
| \`pdfium.wasm\` | \`lib/pdfium.wasm\`, unchanged |
| \`pdfium.mjs\` | \`lib/pdfium.js\`, wrapped into an ES module factory (see the script) |
| \`pdfium.d.mts\` | Written by the script |
| \`VERSION\`, \`args.gn\` | Unchanged: the Chromium version and the GN build arguments |
| \`LICENSE\` | The pdfium-binaries project's licence (MIT) |
| \`licenses/\` | PDFium's licence and those of the libraries built into it |

\`source.json\` holds the same provenance for tools (\`scripts/package.mjs\`).
`;
}

/**
 * List the releases newer than `TAG`, newest first, with the SHA-256 GitHub
 * publishes for each one's `pdfium-wasm.tgz`.
 */
async function check() {
  const pinned = Number(TAG.split("/")[1]);
  const newer: string[] = [];
  for (let page = 1; page <= 10; page++) {
    // Small pages: every release lists dozens of assets, and GitHub times out
    // (504) on 30 of them at once.
    const url = `https://api.github.com/repos/bblanchon/pdfium-binaries/releases?per_page=10&page=${page}`;
    let response = await fetch(url, { headers: { accept: "application/vnd.github+json" } });
    if (response.status >= 500) {
      response = await fetch(url, { headers: { accept: "application/vnd.github+json" } });
    }
    if (!response.ok) fail(`GitHub API: HTTP ${response.status}`);
    const releases = (await response.json()) as Array<{
      tag_name: string;
      published_at: string;
      assets: Array<{ name: string; digest?: string | null }>;
    }>;
    if (releases.length === 0) break;
    let reachedPin = false;
    for (const release of releases) {
      const build = Number(/^chromium\/(\d+)$/.exec(release.tag_name)?.[1]);
      if (!build) continue;
      if (build <= pinned) {
        reachedPin = true;
        continue;
      }
      const asset = release.assets.find((a) => a.name === "pdfium-wasm.tgz");
      const digest = asset?.digest?.replace(/^sha256:/, "") ?? "(no wasm build)";
      newer.push(`${release.tag_name}  ${release.published_at.slice(0, 10)}  ${digest}`);
    }
    if (reachedPin) break;
  }
  console.log(`Pinned: ${TAG}`);
  if (newer.length === 0) {
    console.log("No newer release.");
    return;
  }
  console.log(`${newer.length} newer, newest first (tag, date, SHA-256 of pdfium-wasm.tgz):`);
  for (const line of newer) console.log(`  ${line}`);
}

function sha256(bytes: Uint8Array): string {
  return createHash("sha256").update(bytes).digest("hex");
}

function fail(message: string): never {
  console.error(`vendor_pdfium: ${message}`);
  process.exit(1);
}

async function main() {
  const work = mkdtempSync(join(tmpdir(), "hover-pdfium-"));
  try {
    console.log(`Downloading ${URL}`);
    const response = await fetch(URL);
    if (!response.ok) fail(`download failed: HTTP ${response.status}`);
    const tarball = new Uint8Array(await response.arrayBuffer());
    const actual = sha256(tarball);
    if (actual !== SHA256) {
      fail(`SHA-256 mismatch for ${TAG}\n  expected ${SHA256}\n  got      ${actual}`);
    }
    const tgz = join(work, "pdfium-wasm.tgz");
    writeFileSync(tgz, tarball);

    // Into its own empty directory; nothing in it is run.
    const extracted = join(work, "extracted");
    mkdirSync(extracted);
    execFileSync("tar", ["-xzf", tgz, "-C", extracted]);

    for (const file of ["lib/pdfium.js", "lib/pdfium.wasm", "VERSION", "args.gn", "LICENSE", "licenses"]) {
      if (!existsSync(join(extracted, file))) fail(`the release has no ${file}`);
    }
    const version = readFileSync(join(extracted, "VERSION"), "utf8");
    const build = /^BUILD=(\d+)$/m.exec(version)?.[1];
    if (`chromium/${build}` !== TAG) fail(`VERSION says BUILD=${build}, not ${TAG}`);

    const glue = readFileSync(join(extracted, "lib/pdfium.js"), "utf8");
    if (!glue.includes("onRuntimeInitialized")) {
      fail("lib/pdfium.js doesn't look like Emscripten glue");
    }
    const wasm = readFileSync(join(extracted, "lib/pdfium.wasm"));
    const wasmSha256 = sha256(wasm);

    // Build the whole directory beside the old one, then swap it in.
    const staged = join(work, "pdfium");
    mkdirSync(staged);
    writeFileSync(join(staged, "pdfium.wasm"), wasm);
    writeFileSync(join(staged, "pdfium.mjs"), wrap(glue));
    writeFileSync(join(staged, "pdfium.d.mts"), TYPES);
    for (const file of ["VERSION", "args.gn", "LICENSE"]) {
      cpSync(join(extracted, file), join(staged, file));
    }
    cpSync(join(extracted, "licenses"), join(staged, "licenses"), { recursive: true });
    writeFileSync(
      join(staged, "source.json"),
      JSON.stringify({ tag: TAG, url: URL, sha256: SHA256, wasmSha256 }, null, 2) + "\n",
    );
    writeFileSync(join(staged, "README.md"), readme(wasmSha256));

    mkdirSync(resolve(OUT, ".."), { recursive: true });
    rmSync(OUT, { recursive: true, force: true });
    renameSync(staged, OUT);

    const licences = readdirSync(join(OUT, "licenses")).length;
    console.log(
      `Vendored ${TAG} into vendor/pdfium/: pdfium.wasm ` +
        `${(wasm.length / 1024 ** 2).toFixed(1)} MB, ${licences} licence files`,
    );
  } finally {
    rmSync(work, { recursive: true, force: true });
  }
}

if (process.argv.includes("--check")) await check();
else await main();
